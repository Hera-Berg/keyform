/// The import class of element tag `tag`, if it is a schema type.
pub(crate) fn import_of(tag: &str) -> Option<&'static str> {
    IMPORTS
        .binary_search_by(|(t, _)| (*t).cmp(tag))
        .ok()
        .map(|i| IMPORTS[i].1)
}

/// Every import the elements under `root` need.
pub(crate) fn imports_used(root: &crate::xml::Element) -> std::collections::BTreeSet<&'static str> {
    let mut out = std::collections::BTreeSet::new();
    let mut stack = vec![root];
    while let Some(e) = stack.pop() {
        if let Some(i) = import_of(&e.name) {
            out.insert(i);
        }
        stack.extend(e.children.iter());
    }
    out
}

